#include <stddef.h>

#ifndef CALL_GRAPH_H_
    #define CALL_GRAPH_H_
    #define GRAPH_LIST_SIZE 1024

typedef struct fct_child_name_list {
    char *name;
    struct fct_child_name_list *next;
} fct_child_name_list_t;

typedef struct fct_graph_node {
    char *name;
    char *file;
    fct_child_name_list_t *child;
    size_t max_depth;
    struct fct_graph_node *next;
} fct_graph_node_t;

typedef struct fct_graph {
    fct_graph_node_t *all_node[GRAPH_LIST_SIZE];
    char *current_call;
} fct_graph_t;



/////////////////////////////////////////////////////////////////////////:
/// @brief get the ftrace call stack graph
/////////////////////////////////////////////////////////////////////////:
fct_graph_t *fct_graph_manager(void);

/////////////////////////////////////////////////////////////////////////:
/// @brief init the ftrace call stack graph
/////////////////////////////////////////////////////////////////////////:
void ftrace_graph_init(void);

///////////////////////////////////////////////////////////////////////////:
/// @brief free the ftrace call stack graph
/////////////////////////////////////////////////////////////////////////:
void ftrace_graph_quit(void);

/////////////////////////////////////////////////////////////////////////:
/// @brief create the index of the call in the graph
/// @param str
/// @return the index
/////////////////////////////////////////////////////////////////////////:
size_t hash(char const *str);

/////////////////////////////////////////////////////////////////////////:
/// @brief add a new call in the graph
/// @param str
/// @param depth
/// @param file
/////////////////////////////////////////////////////////////////////////:
void ftrace_graph_add_new_call(char const *str, char const *file, size_t depth);

/////////////////////////////////////////////////////////////////////////:
/// @brief change the current working call
/// @param str
/////////////////////////////////////////////////////////////////////////:
void ftrace_graph_change_current_call(char const *str);

///////////////////////////////////////////////////////////////////////////:
/// @brief store the call graph
///////////////////////////////////////////////////////////////////////////:
void ftrace_graph_store_call_graph(void);

#endif /* !CALL_GRAPH_H_ */
