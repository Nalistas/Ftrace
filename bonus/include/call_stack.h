#include "call_graph.h"

#ifndef CALL_STACK_H_
    #define CALL_STACK_H_

typedef struct call_stack {
    struct call_stack *next;
    char *name;
} call_stack_t;

typedef struct {
    call_stack_t *call_stack;
    size_t call_stack_size;
    fct_graph_t fct_graph;
} ftrace_call_stack_t;

/////////////////////////////////////////////////////////////////////////:
/// @brief init the ftrace_call_stack
/// @param ftrace_call_stack
/////////////////////////////////////////////////////////////////////////:
void ftrace_call_stack_init(void);

/////////////////////////////////////////////////////////////////////////:
/// @brief free the ftrace_call_stack
/// @param ftrace_call_stack
/////////////////////////////////////////////////////////////////////////:
void ftrace_call_stack_quit(void);

/////////////////////////////////////////////////////////////////////////:
/// @brief add a call to the call_stack
/// @param name
/// @param file
/// @param value
/// @return 0 if it is a success, 84 if it is an error
/////////////////////////////////////////////////////////////////////////:
int call_stack_add(char *name, char const *file, long value);

/////////////////////////////////////////////////////////////////////////:
/// @brief pop a call from the call_stack
/// @param ftrace_call_stack
/// @return 0 if it is a success, 84 if it is an error
/////////////////////////////////////////////////////////////////////////:
int call_stack_pop(void);

/////////////////////////////////////////////////////////////////////////:
/// @brief display the graph of the call_stack
/////////////////////////////////////////////////////////////////////////:
void call_stack_graph(void);

#endif /* !CALL_STACK_H_ */
