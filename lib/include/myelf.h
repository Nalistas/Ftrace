#ifndef MYELF_H_
    #define MYELF_H_

    #include "elffile/elf_enum.h"

//////////////////////////////////////////////////////////////////////////////
/// @brief init myelf library
/// @return 0 if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_init(void);

//////////////////////////////////////////////////////////////////////////////
/// @brief quit myelf library
/// @return 0 if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_quit(void);

/////////////////////////////////////////////////////////////////////////////
/// @brief load an elf file
/// @param filename name of the elf file
/// @return id of the elf file if OK, -1 if KO
/////////////////////////////////////////////////////////////////////////////
int myelf_load(const char *filename);

/////////////////////////////////////////////////////////////////////////////
/// @brief unload an elf file
/// @param id id of the elf file
/// @return 0 if OK, -1 if KO
/////////////////////////////////////////////////////////////////////////////
int myelf_unload(int id);

/////////////////////////////////////////////////////////////////////////////
/// @brief get the module type (32-bit or 64-bit)
/// @param id id of the elf file
/// @return 32 if 32-bit, 64 if 64-bit
/////////////////////////////////////////////////////////////////////////////
int myelf_get_mod32x64(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the entry point
/// @param id id of the elf file
/// @return entry point if OK, -1 if KO
/////////////////////////////////////////////////////////////////////////////
int myelf_get_entry(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the symbol table pointer
/// @param id id of the elf file
/// @return symbol table pointer if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
void *myelf_get_symtab_ptr(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the section table pointer
/// @param id id of the elf file
/// @return section table pointer if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
void *myelf_get_shdrtab_ptr(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the segment table pointer
/// @param id id of the elf file
/// @return segment table pointer if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
void *myelf_get_phdrtab_ptr(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the string table pointer
/// @param id id of the elf file
/// @return string table pointer if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
void *myelf_get_strtab_ptr(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief create an iterator on the segment table
/// @param id id of the elf file
/// @return id of the iterator if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_create_phdr_iterator(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief create an iterator on the section table
/// @param id id of the elf file
/// @return id of the iterator if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_create_shdr_iterator(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief create an iterator on the symbol table
/// @param id id of the elf file
/// @return id of the iterator if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_create_sym_iterator(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the iterator pointer
/// @param id id of the iterator file
/// @param id_info id of the information
/// @return offset if OK, 0 if KO
//////////////////////////////////////////////////////////////////////////////
long myelf_get_iterator_info(int id, int id_info);

//////////////////////////////////////////////////////////////////////////////
/// @brief increment the iterator
/// @param id id of the iterator
//////////////////////////////////////////////////////////////////////////////
void myelf_iterator_next(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief check if the iterator has reached the end
/// @param id id of the iterator
/// @return 1 if end, 0 if not
//////////////////////////////////////////////////////////////////////////////
int myelf_iterator_end(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the string table
/// @param id id of the elf file
/// @return string table if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
char const *myelf_get_string_table(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the symbol string table
/// @param id id of the elf file
/// @return symbol string table if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
char const *myelf_get_symstring_table(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the file if already exist
/// @param filename
/// @return the id of the file if OK, -1 if KO
//////////////////////////////////////////////////////////////////////////////
int myelf_get_existant_elf(char const *filename);

/////////////////////////////////////////////////////////////////////////////
/// @brief get the raw file
/// @param id id of the elf file
/// @return raw file if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
char const *myelf_get_raw_file(int id);

//////////////////////////////////////////////////////////////////////////////
/// @brief get the name of the file
/// @param id id of the elf file
/// @return name size if OK, NULL if KO
//////////////////////////////////////////////////////////////////////////////
char const *myelf_get_file_name(int id);

#endif /* !MYELF_H_ */
